// 무료 개방 회차 — 단일 정본 (발주 F-50)
//
//   이 목록 하나가 세 가지를 동시에 결정한다.
//     ① 뷰어 진입 허용   (src/App.jsx — 비로그인·무료 계정도 회차를 열 수 있다)
//     ② pro-data 요청 여부 (src/App.jsx — 무료 로그인 계정도 요청을 보낸다)
//     ③ pro-data 이용권 검사 면제 (api/pro-data.js — 로그인만 확인하고 통과)
//
//   ★ 서버와 클라이언트가 각자 목록을 들고 있으면 한쪽만 고쳐져 갈라진다.
//     F-49 는 서버만 열어 아무것도 열리지 않았다. 그 사고를 막기 위해
//     목록을 이 파일 하나로 묶었다. 회차 추가·회수는 여기만 고친다.
//
//   ★ 의존성을 두지 않는다. api/ 의 서버 함수가 그대로 import 하므로
//     이 파일은 순수 상수·순수 함수만 담는다.
//
//   개방 범위(대표 확정 1단계): 로그인 유지. 비로그인에게 근거·해설을 열지 않는다.
//     "2027_9월" — 유입 후크 한시 개방. 수능(11월) 후 재검토 (F-38).
//     그 밖 5개년 — 최근 수능 무료 범위.

export const FREE_YEARS = [
  "2027_9월",
  "2026수능",
  "2025수능",
  "2024수능",
  "2023수능",
  "2022수능",
];

// 이 회차의 근거·해설(pro 조각)을 이용권 없이 열어 주는가.
//   ★ 로그인 여부는 여기서 판단하지 않는다. 호출부가 각자 확인한다
//     (클라이언트는 user, 서버는 JWT).
export function isFreeProYear(yearKey) {
  return FREE_YEARS.includes(yearKey);
}
